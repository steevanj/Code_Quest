import Editor, { type OnMount } from "@monaco-editor/react";
import type * as Monaco from "monaco-editor";
import { useEffect, useRef } from "react";
import type { Annotation, Diagnostic, FileName, Files, Highlight } from "../types";
import { FILE_NAMES } from "../types";

interface Props {
  files: Files;
  active: string;
  readOnlyFiles: Record<string, string>;
  diagnostics: Diagnostic[];
  annotations: Annotation[];
  highlight: Highlight | null;
  onChange: (file: FileName, text: string) => void;
  onCursor: (file: string, line: number) => void;
}

const SEVERITY = { error: 8, warning: 4, info: 2 } as const;

export default function CodeEditor(props: Props) {
  const { files, active, readOnlyFiles, diagnostics, annotations, highlight, onChange, onCursor } = props;
  const editorRef = useRef<Monaco.editor.IStandaloneCodeEditor | null>(null);
  const monacoRef = useRef<typeof Monaco | null>(null);
  const decorations = useRef<Monaco.editor.IEditorDecorationsCollection | null>(null);
  const activeRef = useRef(active);
  activeRef.current = active;
  const onCursorRef = useRef(onCursor);
  onCursorRef.current = onCursor;

  const readOnly = !FILE_NAMES.includes(active as FileName);
  const value = readOnly ? readOnlyFiles[active] ?? "" : files[active as FileName];

  const handleMount: OnMount = (editor, monaco) => {
    editorRef.current = editor;
    monacoRef.current = monaco;
    decorations.current = editor.createDecorationsCollection();
    editor.onDidChangeCursorPosition((e) => onCursorRef.current(activeRef.current, e.position.lineNumber));
  };

  // Diagnostics → squiggles, for every open model.
  useEffect(() => {
    const monaco = monacoRef.current;
    if (!monaco) return;
    for (const model of monaco.editor.getModels()) {
      const name = model.uri.path.replace(/^\//, "");
      const markers = diagnostics
        .filter((d) => d.file === name)
        .map((d) => {
          const count = model.getLineCount();
          const line = Math.min(d.line, count);
          // Whole-line markers for line-only diagnostics and for large nodes (e.g. a whole class).
          const whole = d.end_col === null || (d.end_line ?? d.line) - d.line > 2;
          const endLine = whole ? line : Math.min(d.end_line ?? d.line, count);
          return {
            severity: SEVERITY[d.severity],
            message: d.hint ? `${d.message}\n\nHint: ${d.hint}` : d.message,
            startLineNumber: line,
            startColumn: whole ? Math.max(1, model.getLineFirstNonWhitespaceColumn(line)) : d.col + 1,
            endLineNumber: endLine,
            endColumn: whole ? model.getLineMaxColumn(line) : (d.end_col ?? 0) + 1,
          };
        });
      monaco.editor.setModelMarkers(model, "forge", markers);
    }
  }, [diagnostics, active, value]);

  // Teachable lines + execution/error highlight.
  useEffect(() => {
    const monaco = monacoRef.current;
    const editor = editorRef.current;
    if (!monaco || !editor || !decorations.current) return;
    const items: Monaco.editor.IModelDeltaDecoration[] = [];
    const taught = new Set<number>();
    for (const a of annotations) if (a.file === active && a.kind !== "import") taught.add(a.line);
    for (const line of taught) {
      items.push({ range: new monaco.Range(line, 1, line, 1), options: { linesDecorationsClassName: "teach-mark" } });
    }
    if (highlight && highlight.file === active) {
      const end = highlight.endLine ?? highlight.line;
      items.push({
        range: new monaco.Range(highlight.line, 1, end, 1),
        options: {
          isWholeLine: true,
          className: highlight.tone === "error" ? "line-error" : "line-flow",
          linesDecorationsClassName: highlight.tone === "error" ? "gutter-error" : "gutter-flow",
        },
      });
      editor.revealLineInCenterIfOutsideViewport(highlight.line);
    }
    decorations.current.set(items);
  }, [annotations, highlight, active, value]);

  return (
    <div className="editor-host">
      {readOnly && <div className="readonly-banner">Generated by makemigrations · read-only</div>}
      <Editor
        path={active}
        language="python"
        theme="forge"
        value={value}
        onMount={handleMount}
        onChange={(text) => !readOnly && onChange(active as FileName, text ?? "")}
        options={{
          readOnly,
          fontFamily: "'JetBrains Mono', Consolas, monospace",
          fontSize: 13.5,
          lineHeight: 21,
          minimap: { enabled: false },
          scrollBeyondLastLine: false,
          renderLineHighlight: "all",
          tabSize: 4,
          insertSpaces: true,
          automaticLayout: true,
          padding: { top: 12 },
          smoothScrolling: true,
          glyphMargin: false,
          lineDecorationsWidth: 14,
        }}
      />
    </div>
  );
}
